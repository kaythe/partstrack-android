/** The app's main screen. For now it only shows the connection; the parts list follows. */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun PartsScreen(settings: Settings, onOpenSettings: () -> Unit) {
    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text(stringResource(R.string.app_name)) },
                actions = {
                    IconButton(onClick = onOpenSettings) {
                        Icon(Icons.Filled.Settings, contentDescription = stringResource(R.string.settings_title))
                    }
                },
            )
        },
    ) { padding ->
        Column(
            modifier = Modifier.fillMaxSize().padding(padding).padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(8.dp, Alignment.CenterVertically),
            horizontalAlignment = Alignment.CenterHorizontally,
        ) {
            Text(settings.serverUrl?.toString() ?: "", style = MaterialTheme.typography.titleMedium)
            Text(
                stringResource(if (settings.canWrite) R.string.mode_read_write else R.string.mode_read_only),
                style = MaterialTheme.typography.bodyMedium,
            )
        }
    }
}
